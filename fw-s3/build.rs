//! Emits `ram-layout.x`, placing the previous-frame framebuffer at the top of
//! `dram2_seg` (bootloader-reclaimed SRAM) and extending `_stack_start` up to it
//! so `.bss` and the main stack share the full internal DRAM budget.

use std::env;
use std::fs;
use std::path::PathBuf;

/// Must equal `size_of::<display::fb::Framebuffer>()`: 800x480 / 8 + 1 frame byte.
const PREV_FB_BYTES: usize = (800 / 8 * 480) + 1;

/// Minimum main-stack headroom (`_stack_start - _stack_end`) above the ~27 KiB
/// EPUB-open peak.
const MIN_STACK_BYTES: usize = 28 * 1024;

fn main() {
    println!("cargo:rerun-if-env-changed=BENCH_SCENARIO");
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let script = format!(
        r#"/* Generated by fw-s3/build.rs - do not edit. */

_prev_fb_slot = (ORIGIN(dram2_seg) + LENGTH(dram2_seg) - {fb}) & 0xFFFFFFFC;

SECTIONS {{
  .dram2_prev_fb _prev_fb_slot (NOLOAD) :
  {{
    KEEP(*(.dram2_prev_fb .dram2_prev_fb.*));
  }}
}}

ASSERT(SIZEOF(.dram2_prev_fb) == {fb} || SIZEOF(.dram2_prev_fb) == 0,
       ".dram2_prev_fb size differs from fw-s3/build.rs PREV_FB_BYTES");
ASSERT(_dram2_uninit_bss_end == _dram2_uninit_bss_start,
       ".dram2_uninit overlap is unsupported with custom _stack_start");

_stack_start = _prev_fb_slot & 0xFFFFFFF0;
_stack_start_cpu0 = _stack_start;

ASSERT(_stack_start - _stack_end >= {min_stack},
       "main stack under budget; trim statics or rebalance dram2 (see fw-s3/build.rs)");
"#,
        fb = PREV_FB_BYTES,
        min_stack = MIN_STACK_BYTES,
    );

    fs::write(out_dir.join("ram-layout.x"), script).unwrap();
    println!("cargo:rustc-link-search={}", out_dir.display());
    println!("cargo:rustc-link-arg-bins=-Tlinkall.x");
    println!("cargo:rustc-link-arg-bins=-Tram-layout.x");
}
